// Generates realistic equity curve data points for given account
export function generateEquityCurve(accountId: string, timeframe: string): EquityDataPoint[] {
  const pointsCount =
    timeframe === '1D'
      ? 24
      : timeframe === '1W'
      ? 28
      : timeframe === '1M'
      ? 30
      : timeframe === '3M'
      ? 45
      : timeframe === '6M'
      ? 60
      : timeframe === '1Y'
      ? 90
      : 120;

  const baseBalance =
    accountId === 'acc-main-01'
      ? 22500
      : accountId === 'acc-test-02'
      ? 10500
      : accountId === 'acc-strat-03'
      ? 5000
      : 38000; // All accounts

  const trendMultiplier =
    accountId === 'acc-main-01'
      ? 1.0025
      : accountId === 'acc-test-02'
      ? 0.9992
      : accountId === 'acc-strat-03'
      ? 1.0018
      : 1.002;

  const points: EquityDataPoint[] = [];
  let currentBalance = baseBalance;
  const now = new Date();

  for (let i = pointsCount - 1; i >= 0; i--) {
    const d = new Date(now.getTime() - i * (86400000 / (pointsCount > 30 ? 1 : pointsCount > 24 ? 2 : 24)));
    const randomWiggle = (Math.sin(i * 0.45) * 0.005 + (Math.cos(i * 0.8) * 0.004)) * currentBalance;
    currentBalance = currentBalance * trendMultiplier + randomWiggle;
    const floatingWiggle = (Math.sin(i * 1.2) * 0.003) * currentBalance;
    const equity = currentBalance + floatingWiggle;
    const pl = currentBalance - baseBalance;
    const maxSeen = Math.max(baseBalance * 1.05, currentBalance);
    const drawdown = Number((((maxSeen - currentBalance) / maxSeen) * 100).toFixed(1));

    points.push({
      date: timeframe === '1D' 
        ? d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) 
        : d.toLocaleDateString([], { month: 'short', day: 'numeric' }),
      timestamp: d.getTime(),
      balance: Math.round(currentBalance * 100) / 100,
      equity: Math.round(equity * 100) / 100,
      drawdown: Math.max(0, drawdown),
      pl: Math.round(pl * 100) / 100,
    });
  }

  return points;
}
